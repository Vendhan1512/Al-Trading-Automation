// Generates typed ABIs from Foundry build output: node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
const out = (n) => JSON.parse(readFileSync(`../contracts/out/${n}.sol/${n}.json`, "utf8")).abi;
for (const [n, file] of [["CountersignVault", "countersignVault"], ["VaultFactory", "vaultFactory"]]) {
  writeFileSync(`src/abi/${file}.ts`, `// GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit\nexport const ${file}Abi = ${JSON.stringify(out(n), null, 2)} as const;\n`);
  console.log(`src/abi/${file}.ts`);
}
